/// `C = A @ B` with explicit parallelism control, both arms on gemmkit's kernels
///
/// `A` is `(m, k)`, `B` is `(k, n)`; the result is a freshly allocated, standard-layout `(m, n)`
/// array. Any storage works (owned, view, transpose, slice; strides pass through zero-copy)
///
/// - `parallel == false`: one serial gemmkit call (`Parallelism::Serial`) - still the SIMD
///   kernel, just on one thread. Use this to force a product serial from inside an
///   already-parallel region, so it does not fork rayon again (nested parallelism /
///   oversubscription)
/// - `parallel == true`: gemmkit auto parallelism (`Parallelism::Rayon(0)`) - the backend gates
///   serial-vs-parallel on the work size and picks the worker count and split itself
///
/// Callers with no opinion on parallelism should use [`gemm_par_auto`] instead
///
/// # Panics
///
/// - If `A`'s column count differs from `B`'s row count
#[cfg(any(
    feature = "machine_learning",
    feature = "neural_network",
    feature = "utils"
))]
pub(crate) fn gemm_par_switch<T, S1, S2>(
    a: &ArrayBase<S1, Ix2>,
    b: &ArrayBase<S2, Ix2>,
    parallel: bool,
) -> Array2<T>
where
    T: gemmkit::GemmScalar,
    S1: Data<Elem = T>,
    S2: Data<Elem = T>,
{
    let (m, k) = a.dim();
    let (kb, n) = b.dim();
    assert_eq!(
        k, kb,
        "gemm_par_switch: inner dimensions disagree (a is {m}x{k}, b is {kb}x{n})",
    );
    let par = if parallel {
        gemmkit::Parallelism::Rayon(0)
    } else {
        gemmkit::Parallelism::Serial
    };
    // `beta == 0` means the fill value is never read; `from_elem` avoids a `Zero` bound
    let mut c = Array2::from_elem((m, n), T::ZERO);
    gemmkit_ndarray::gemm(T::ONE, a, b, T::ZERO, &mut c, par);
    c
}

/// `C = A @ B` on gemmkit's automatic scheduling
///
/// Serial below the backend's work gate (the per-call dispatch would dominate the tiny products
/// in tight loops, e.g. RNN/LSTM timesteps); above it the backend picks the worker count and the
/// split. This is the entry for callers that have no opinion on parallelism;
/// [`gemm_par_switch`] is the entry for callers that must control it explicitly
///
/// # Panics
///
/// - If `A`'s column count differs from `B`'s row count
#[cfg(any(
    feature = "machine_learning",
    feature = "neural_network",
    feature = "utils"
))]
pub(crate) fn gemm_par_auto<T, S1, S2>(a: &ArrayBase<S1, Ix2>, b: &ArrayBase<S2, Ix2>) -> Array2<T>
where
    T: gemmkit::GemmScalar,
    S1: Data<Elem = T>,
    S2: Data<Elem = T>,
{
    gemm_par_switch(a, b, true)
}

/// `y = A @ x` with explicit parallelism control (the GEMV analogue of [`gemm_par_switch`])
///
/// `A` is `(m, k)`, `x` has length `k`; the result has length `m`
/// - `parallel == false`: one serial gemmkit call. Use this to force a matvec serial from inside
///   an already-parallel region so it does not fork rayon again
/// - `parallel == true`: gemmkit auto parallelism - the backend detects the `n == 1` shape and
///   runs its bandwidth-bound GEMV path (serial below an LLC-derived byte floor, then split
///   across the memory-bandwidth worker cap)
///
/// Callers with no opinion on parallelism should use [`gemv_par_auto`] instead
///
/// # Panics
///
/// - If `A`'s column count differs from `x`'s length
#[cfg(feature = "machine_learning")]
pub(crate) fn gemv_par_switch<T, S1, S2>(
    a: &ArrayBase<S1, Ix2>,
    x: &ArrayBase<S2, Ix1>,
    parallel: bool,
) -> Array1<T>
where
    T: gemmkit::GemmScalar,
    S1: Data<Elem = T>,
    S2: Data<Elem = T>,
{
    use ndarray::Axis;

    let (m, k) = a.dim();
    assert_eq!(
        k,
        x.len(),
        "gemv_par_switch: inner dimensions disagree (a is {m}x{k}, x has length {})",
        x.len()
    );
    let par = if parallel {
        gemmkit::Parallelism::Rayon(0)
    } else {
        gemmkit::Parallelism::Serial
    };
    // Treat the vector as a single-column matrix; gemmkit reroutes `n == 1` to its GEMV path
    let x_col = x.view().insert_axis(Axis(1)); // [k, 1]
    let mut y = Array1::from_elem(m, T::ZERO);
    let mut y_col = y.view_mut().insert_axis(Axis(1)); // [m, 1]
    gemmkit_ndarray::gemm(T::ONE, a, &x_col, T::ZERO, &mut y_col, par);
    y
}

/// `y = A @ x` on gemmkit's automatic scheduling (the GEMV analogue of [`gemm_par_auto`])
///
/// `A` is `(m, k)`, `x` has length `k`; the result has length `m`. The backend gates the matvec
/// on bytes touched (a matvec is memory-bound: serial while the operands are cache-resident,
/// split across the bandwidth worker cap once they stream from DRAM)
///
/// # Panics
///
/// - If `A`'s column count differs from `x`'s length
#[cfg(feature = "machine_learning")]
pub(crate) fn gemv_par_auto<T, S1, S2>(a: &ArrayBase<S1, Ix2>, x: &ArrayBase<S2, Ix1>) -> Array1<T>
where
    T: gemmkit::GemmScalar,
    S1: Data<Elem = T>,
    S2: Data<Elem = T>,
{
    gemv_par_switch(a, x, true)
}

tunable_gate! {
    /// Element budget for one row-chunk of a tiled product whose full result would be too large
    /// to materialize at once (e.g. KNN's `[n_query, n_train]` projections or t-SNE's pairwise
    /// blocks): `chunk_rows = gemm_chunk_elems() / row_len`, clamped to `[16, 4096]` rows
    ///
    /// Tiling only pays when the shared operand overflows the cache (see `cache_resident`); there
    /// bigger chunks are strictly better, so the budget caps the transient chunk buffer at 256 MB
    /// of `f64` rather than chasing the asymptote. Overridable via [`crate::tuning::matmul`]
    pub(crate) GEMM_CHUNK_ELEMS => gemm_chunk_elems / set_gemm_chunk_elems = 33_554_432
}

/// Rows per chunk when tiling a product with `row_len`-wide output rows under `gemm_chunk_elems`
///
/// Crate-internal tiling policy; not part of the public API and carries no stability guarantee
#[doc(hidden)]
pub fn gemm_chunk_rows(row_len: usize) -> usize {
    (gemm_chunk_elems() / row_len.max(1)).clamp(16, 4096)
}

tunable_gate! {
    /// Matrix size (bytes) below which repeated row-GEMV sweeps over a shared matrix stay
    /// cache-resident, making a per-row GEMV swarm faster than a tiled GEMM
    ///
    /// When many tasks each compute `X . v` against the same `X`, the whole of `X` is re-read per
    /// task - free while `X` fits in the shared L3, but a DRAM re-stream once it overflows, where a
    /// tiled GEMM (which streams `X` once per chunk) wins instead. The default sits at a typical
    /// L3 size; the band around it is uncalibrated. Overridable via [`crate::tuning::matmul`] - the
    /// natural knob to match a machine's actual L3
    pub(crate) CACHE_RESIDENT_MAX_BYTES
        => cache_resident_max_bytes / set_cache_resident_max_bytes = 64 * 1024 * 1024
}

/// Whether an `[rows, cols]` matrix of `T` is small enough to treat as cache-resident for
/// repeated row-GEMV sweeps (see `cache_resident_max_bytes`)
///
/// Crate-internal strategy policy; not part of the public API and carries no stability
/// guarantee
#[doc(hidden)]
pub fn cache_resident<T>(rows: usize, cols: usize) -> bool {
    rows.saturating_mul(cols)
        .saturating_mul(std::mem::size_of::<T>())
        < cache_resident_max_bytes()
}

