//! Matrix products for ndarray operands, backed by the [`gemmkit`](https://docs.rs/gemmkit)
//! engine (through its zero-copy [`gemmkit-ndarray`](https://docs.rs/gemmkit-ndarray) adapter)
//!
//! Every product runs on gemmkit's kernels - runtime-dispatched to the widest available SIMD
//! (AVX-512F / FMA / NEON / wasm simd128 over a scalar floor), with operand packing, and
//! automatic reroutes for the bandwidth-bound shapes (matvec `n == 1`, small-`m,n`, small-`k`).
//! Scheduling is gemmkit's own:
//!
//! - **Auto parallelism** (`Parallelism::Rayon(0)`, the `gemm_par_auto` / `gemv_par_auto`
//!   default): a work gate (`m*n*k` below `GEMMKIT_PARALLEL_THRESHOLD` runs serial, so the tiny
//!   products in tight loops - RNN/LSTM timesteps - skip the dispatch cost entirely), then a
//!   work-based worker ramp snapped to persistent exact-fit thread-pool tiers. A matvec instead
//!   gates on bytes touched against an LLC-derived floor and jumps to a memory-bandwidth cap -
//!   the backend parallelizes GEMV itself, so this crate no longer row-splits by hand
//! - **Forced serial** (`gemm_par_switch` / `gemv_par_switch` with `parallel == false`,
//!   `Parallelism::Serial`): still gemmkit's SIMD kernel, on the calling thread only. Callers
//!   inside an already-parallel rayon region use this so the product does not fork again
//!
//! Calls made from inside a rayon worker run on the caller's pool (gemmkit detects nesting), so
//! these wrappers also compose safely inside a rayon region
//!
//! ## Tuning
//!
//! The scheduling knobs live in gemmkit, not this crate: every threshold is a `GEMMKIT_*`
//! environment variable (read once per process), programmatically settable via
//! [`crate::tuning::matmul::backend`], and a whole-machine profile can be generated by the
//! [`gemmkit-tune`](https://docs.rs/gemmkit-tune) autotuner and `source`d before launch
//!
//! ## Reproducibility
//!
//! gemmkit's blocking and job order are independent of the worker count, so for a fixed machine
//! and configuration the same product reproduces the same result bit-for-bit, no matter how many
//! threads ran it (and re-running is deterministic). Fused epilogues (bias / activation / map)
//! are bitwise-identical to the plain product followed by the same scalar map
//!
//! `gemm_chunk_rows` and `cache_resident` remain as tiling-strategy helpers for callers that
//! materialize a product in row-chunks (KNN, t-SNE, MeanShift)

